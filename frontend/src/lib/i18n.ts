const dictionaries: Record<AppLanguage, Dictionary> = {
  'zh-CN': zhCN,
  en: enUS,
}

const formatMessage = (template: string, params?: Record<string, string | number>) => {
  if (!params) return template
  return Object.entries(params).reduce(
    (result, [key, value]) => result.replaceAll(`{{${key}}}`, String(value)),
    template,
  )
}

export const createTranslator = (language: AppLanguage = 'zh-CN') => {
  const dictionary = dictionaries[language] || zhCN
  return (key: string, params?: Record<string, string | number>) => {
    const template = dictionary[key] || zhCN[key] || key
    return formatMessage(template, params)
  }
}

export const translateRole = (language: AppLanguage, role?: string, fallback?: string) => {
  if (!role) return fallback || createTranslator(language)('common.unknownRole')
  const translated = createTranslator(language)(`role.${role}`)
  if (translated === `role.${role}`) {
    return fallback || role
  }
  return translated
}

export const translateLeaveStatus = (language: AppLanguage, status: string) => {
  const translated = createTranslator(language)(`leaveStatus.${status}`)
  if (translated === `leaveStatus.${status}`) {
    return status
  }
  return translated
}

export const translateNotificationType = (language: AppLanguage, type: string, fallback?: string) => {
  const translated = createTranslator(language)(`notificationType.${type}`)
  if (translated === `notificationType.${type}`) {
    return fallback || type
  }
  return translated
}

export const useI18n = () => {
  const language = (useAuthStore((state) => state.user?.language || state.uiPreferences.language) || 'zh-CN') as AppLanguage
  const t = useMemo(() => createTranslator(language), [language])

  return {
    language,
    isEnglish: language === 'en',
    t,
    roleLabel: (role?: string, fallback?: string) => translateRole(language, role, fallback),
    leaveStatusLabel: (status: string) => translateLeaveStatus(language, status),
    notificationTypeLabel: (type: string, fallback?: string) => translateNotificationType(language, type, fallback),
  }
}
